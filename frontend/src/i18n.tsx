interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function readStoredLanguage(): Language {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en' ? 'en' : 'vi';
  } catch (error) {
    console.error('Could not read language preference:', error);
    return 'vi';
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(readStoredLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    } catch (error) {
      console.error('Could not save language preference:', error);
    }
  }, [language]);

  const t = useCallback((key: string, values?: Record<string, string | number>) => {
    let result = language === 'en' ? (english[key] ?? key) : key;
    if (values) {
      Object.entries(values).forEach(([name, value]) => {
        result = result.replaceAll(`{{${name}}}`, String(value));
      });
    }
    return result;
  }, [language]);

  const contextValue = useMemo(() => ({ language, setLanguage, t }), [language, t]);

  return (
    <LanguageContext.Provider value={contextValue}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}
